import React from 'react';
// Importação dos ícones do pacote padrão do projeto (react-icons/fa)
import { 
    FaPhone,        // Para Ligações
    FaEnvelope,     // Para Emails
    FaWhatsapp,     // Para conversas de Zap
    FaStickyNote,   // Para notas gerais/padrão
    FaCalendarAlt,  // Para reuniões/agendamentos
    FaRobot,        // Badge para indicar conteúdo gerado por IA
    FaUser          // Fallback genérico
} from 'react-icons/fa'; 

// Importamos os tipos que definimos anteriormente para garantir tipagem forte
import { CRMInteraction, InteractionType } from '../../types';

interface InteractionTimelineProps {
    interactions: CRMInteraction[]; // A lista de dados já tratada pelo Hook
    loading?: boolean;              // Estado de carregamento para feedback visual
}

/**
 * Componente InteractionTimeline
 * * Responsável por renderizar a linha do tempo de interações do cliente.
 * Suporta visualização diferenciada para notas manuais vs. geradas por IA.
 */
export const InteractionTimeline: React.FC<InteractionTimelineProps> = ({ 
    interactions, 
    loading 
}) => {

    /**
     * HELPER: getIconInfo
     * Centraliza a lógica visual. Recebe o TIPO de interação e devolve:
     * 1. O Ícone correspondente (Componente React)
     * 2. A cor do texto (Tailwind class)
     * 3. A cor de fundo com opacidade (Tailwind class)
     */
    const getIconInfo = (type: InteractionType) => {
        switch (type) {
            case InteractionType.CALL:
                return { 
                    icon: FaPhone, 
                    color: 'text-blue-400', 
                    bg: 'bg-blue-400/10' 
                };
            case InteractionType.MEETING:
                return { 
                    icon: FaCalendarAlt, 
                    color: 'text-purple-400', 
                    bg: 'bg-purple-400/10' 
                };
            case InteractionType.EMAIL:
                return { 
                    icon: FaEnvelope, 
                    color: 'text-yellow-400', 
                    bg: 'bg-yellow-400/10' 
                };
            case InteractionType.WHATSAPP:
                return { 
                    icon: FaWhatsapp, 
                    color: 'text-green-400', 
                    bg: 'bg-green-400/10' 
                };
            case InteractionType.NOTE:
            default:
                // Fallback neutro para notas gerais
                return { 
                    icon: FaStickyNote, 
                    color: 'text-gray-400', 
                    bg: 'bg-gray-400/10' 
                };
        }
    };

    /**
     * HELPER: formatDate
     * Formata a data ISO do banco para o padrão brasileiro legível.
     * Ex: "10 de jan., 14:30"
     */
    const formatDate = (dateString: string) => {
        if (!dateString) return '';
        try {
            return new Intl.DateTimeFormat('pt-BR', {
                day: '2-digit',
                month: 'short',
                hour: '2-digit',
                minute: '2-digit'
            }).format(new Date(dateString));
        } catch (e) {
            return dateString; // Fallback se a data vier inválida
        }
    };

    // --- RENDERIZAÇÃO: ESTADO DE LOADING ---
    if (loading) {
        return (
            <div className="p-8 flex flex-col items-center justify-center text-gray-500 animate-pulse">
                <FaStickyNote className="w-8 h-8 mb-2 opacity-50" />
                <span className="text-sm font-medium">Carregando histórico...</span>
            </div>
        );
    }

    // --- RENDERIZAÇÃO: LISTA VAZIA ---
    if (interactions.length === 0) {
        return (
            <div className="flex flex-col items-center justify-center py-12 px-4 text-center text-gray-500 border-2 border-dashed border-gray-700 rounded-xl bg-gray-800/20">
                <FaStickyNote className="w-12 h-12 mb-3 opacity-20" />
                <p className="font-medium text-gray-300">Nenhuma interação registrada.</p>
                <span className="text-sm opacity-60 mt-1">
                    Use o campo abaixo para criar a primeira nota ou agendar uma tarefa.
                </span>
            </div>
        );
    }

    // --- RENDERIZAÇÃO: LISTA DE DADOS ---
    return (
        <div className="space-y-6 relative">
            {interactions.map((interaction, index) => {
                // Extrai as cores e ícones baseados no tipo
                const { icon: Icon, color, bg } = getIconInfo(interaction.type);
                
                // Flag que indica se foi o Agente de IA que criou/tocou nesta nota
                const isAI = interaction.autoGenerated;
                
                // Verifica se é o último item para esconder a linha conectora
                const isLastItem = index === interactions.length - 1;

                return (
                    <div key={interaction.id} className="relative flex gap-4 group">
                        
                        {/* ========================================================
                            1. LINHA DO TEMPO (CONECTOR VERTICAL)
                           ======================================================== */}
                        {!isLastItem && (
                            <div 
                                className="absolute top-10 left-[19px] bottom-[-24px] w-0.5 bg-gray-800"
                                aria-hidden="true"
                            ></div>
                        )}

                        {/* ========================================================
                            2. BOLHA DO ÍCONE (Avatar da Interação)
                           ======================================================== */}
                        <div className={`
                            relative z-10 flex items-center justify-center 
                            w-10 h-10 rounded-full shrink-0 
                            ${bg} ${color} 
                            border border-gray-700/50 shadow-sm transition-transform hover:scale-105
                        `}>
                            <Icon size={16} />
                            
                            {/* Badge "Robozinho": Aparece apenas se for IA */}
                            {isAI && (
                                <div 
                                    className="absolute -bottom-1 -right-1 bg-accent-primary text-base-dark rounded-full p-1 border border-base-metallic shadow-md" 
                                    title="Gerado automaticamente pela IA"
                                >
                                    <FaRobot size={8} />
                                </div>
                            )}
                        </div>

                        {/* ========================================================
                            3. CONTEÚDO (CARD DIREITO)
                           ======================================================== */}
                        <div className="flex-1 min-w-0">
                            
                            {/* Cabeçalho do Card: Quem e Quando */}
                            <div className="flex items-center justify-between mb-1.5">
                                <div className="flex items-center gap-2">
                                    {/* Nome do Autor: Se for IA, destaca com cor de accent */}
                                    <span className={`text-sm font-bold ${isAI ? 'text-accent-primary' : 'text-gray-200'}`}>
                                        {isAI ? 'Resumo Automático' : (interaction.userName || 'Usuário')}
                                    </span>
                                    
                                    <span className="text-xs text-gray-600">•</span>
                                    
                                    {/* Tipo da interação (Call, Email...) */}
                                    <span className="text-[10px] font-semibold uppercase tracking-wider text-gray-500 bg-gray-800 px-1.5 py-0.5 rounded">
                                        {interaction.type}
                                    </span>
                                </div>
                                
                                {/* Data Formatada */}
                                <time className="text-xs text-gray-500 font-mono">
                                    {formatDate(interaction.createdAt)}
                                </time>
                            </div>

                            {/* Corpo do Texto */}
                            <div className={`
                                p-4 rounded-lg border transition-colors duration-200
                                ${isAI ? 'bg-gray-800/80 border-accent-primary/20' : 'bg-gray-800/40 border-gray-700/50'}
                                hover:border-gray-600
                            `}>
                                <p className="text-sm text-gray-300 whitespace-pre-wrap leading-relaxed">
                                    {interaction.content}
                                </p>
                                
                                {/* ================================================
                                    4. ÁREA DE METADADOS DA IA (Tags)
                                    Renderiza tags apenas se a IA tiver analisado
                                   ================================================ */}
                                {interaction.aiMetadata?.analysis?.tags && interaction.aiMetadata.analysis.tags.length > 0 && (
                                    <div className="mt-3 pt-3 border-t border-gray-700/50 flex flex-wrap gap-2">
                                        {interaction.aiMetadata.analysis.tags.map((tag: string) => (
                                            <span 
                                                key={tag} 
                                                className="px-2 py-0.5 text-[10px] uppercase tracking-wider font-bold text-gray-400 bg-gray-700/50 rounded hover:bg-gray-700 hover:text-gray-200 cursor-default transition-colors"
                                            >
                                                #{tag}
                                            </span>
                                        ))}
                                    </div>
                                )}
                            </div>
                        </div>
                    </div>
                );
            })}
        </div>
    );
};