export enum InteractionType {
    CALL = 'CALL',           // Ícone: Telefone
    MEETING = 'MEETING',     // Ícone: Calendário/Pessoas
    EMAIL = 'EMAIL',         // Ícone: Envelope
    NOTE = 'NOTE',           // Ícone: Nota Adesiva
    WHATSAPP = 'WHATSAPP',   // Ícone: Logo Zap (NOVO)
    AUDIO = 'AUDIO'          // Mantido para compatibilidade visual
}

// ============================================================================
// 2. ESTRUTURAS DO AGENTE INTELIGENTE (NOVO - OPÇÃO B)
// ============================================================================

/**
 * Define o tipo de ação que o Agente está sugerindo realizar.
 */
export type AgentActionType = 
    | 'UPDATE_CLIENT_DATA'   // Ex: Mudar telefone, email
    | 'UPDATE_DEAL_STAGE'    // Ex: Mover de Negociação para Ganho
    | 'SCHEDULE_TASK'        // Ex: Criar lembrete na agenda
    | 'LOG_RISK'             // Ex: Marcar cliente como risco de Churn
    | 'NONE';                // Apenas registrar a nota

/**
 * A estrutura da "Proposta" que aparece na tela para o usuário confirmar.
 * Isso habilita o fluxo Human-in-the-Loop.
 */
export interface AgentProposal {
    id: string;              // ID temporário para controle da UI
    confidence: number;      // 0.0 a 1.0 (Para exibir alertas se a confiança for baixa)
    
    // O Racional: Por que a IA está sugerindo isso?
    reasoning: string;       // Ex: "O cliente mencionou explicitamente que o orçamento foi aprovado."
    
    // A Ação Sugerida
    action: AgentActionType;
    
    // Payload Dinâmico (Dados da mudança)
    data: {
        targetEntity: 'CLIENT' | 'DEAL' | 'TASK';
        targetId?: string;    // ID do Cliente ou Deal alvo
        
        // Mudanças propostas (Para diff visual: De -> Para)
        changes?: Array<{
            field: string;    // Ex: 'temperature', 'status'
            label: string;    // Nome amigável para exibir na tela (Ex: "Temperatura")
            oldValue?: any;
            newValue: any;
        }>;
    };
}

// ============================================================================
// 3. ESTRUTURAS DE ANÁLISE DE DADOS (EXPANDIDO)
// ============================================================================

export interface ExtractedAddress {
    street: string | null;
    number: string | null;
    complement: string | null;
    district: string | null;
    city: string | null;
    state: string | null;
    zipCode: string | null;
    type: "MAIN" | "BILLING" | "SHIPPING" | null;
}

/**
 * Metadados ricos gerados pela IA.
 * Agora vive dentro de `aiMetadata` na interação principal.
 */
export interface InteractionAnalysis {
    summary: string;
    sentiment: "POSITIVE" | "NEUTRAL" | "NEGATIVE" | "TENSE";
    tags: string[];
    actionItems: string[]; // Tarefas sugeridas
    
    // Probabilidade calculada para o Deal (0-100)
    dealProbability?: number;
    
    // Dados extraídos do texto (Entidades)
    extractedIdentity?: {
        personName: string | null;
        companyName: string | null;
        email: string | null;
        phone: string | null;
        extractedAddresses?: ExtractedAddress[];
        intentType: "NEW_BUSINESS" | "SUPPORT" | "FOLLOW_UP" | "UNKNOWN" | "CHURN_RISK";
    };
}

// ============================================================================
// 4. ENTIDADES PRINCIPAIS (INTERAÇÃO UNIFICADA)
// ============================================================================

/**
 * Representa uma interação na Timeline.
 * Adaptada para receber os dados do novo Backend (ai_interactions).
 */
export interface CRMInteraction {
    id: string;
    tenantId?: string; // Opcional no front
    clientId?: string; // Opcional no front pois já estamos no contexto do cliente
    
    type: InteractionType;
    content: string; // O texto principal (Input ou Output da IA)
    
    createdAt: string; // ISO Date
    userId: string;
    userName?: string; // Nome/Email de quem criou

    // --- NOVOS CAMPOS DE INTELIGÊNCIA ---
    
    // Se true, foi gerado automaticamente pelo sistema/IA
    autoGenerated?: boolean; 
    
    // Container flexível para os metadados vindos do banco
    aiMetadata?: {
        manual?: boolean;
        originalType?: string;
        analysis?: InteractionAnalysis; // A análise detalhada (Sentimento, Tags)
        proposal?: AgentProposal;       // Se houver uma proposta pendente vinculada a esta nota
        mediaUrl?: string;              // Para áudios transcritos
    };

    // Mantido para compatibilidade imediata com componentes antigos
    // (Idealmente, o componente deve ler de aiMetadata.analysis)
    aiAnalysis?: InteractionAnalysis; 
}