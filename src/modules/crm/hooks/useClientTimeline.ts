import { useState, useCallback } from 'react';
import { api } from '@/core/services/api'; // Importa o cliente HTTP que criamos
import { 
    CRMInteraction, 
    InteractionType, 
    AgentProposal 
} from '../types';

/**
 * Interface Interna (DTO):
 * Representa exatamente o JSON que o Backend envia.
 * Não exportamos isso pois a UI não deve conhecer essa estrutura "crua".
 */
interface BackendInteractionDto {
    id: string;
    type: string; // O backend manda string ('NOTE', 'CALL', etc.)
    content: string;
    createdAt: string;
    userId: string;
    userName?: string;
    
    // O coração da inteligência: Metadados opcionais
    aiMetadata?: {
        manual?: boolean;       // True = Feito por humano
        originalType?: string;  // Tipo original
        analysis?: any;         // Análise de sentimento, tags
        proposal?: AgentProposal; // Se a IA sugeriu uma ação (Ex: Mudar status)
    };
}

/**
 * HOOK: useClientTimeline
 * Responsável por gerenciar todo o ciclo de vida das interações de um cliente específico.
 * * @param clientId - O ID do cliente que estamos visualizando.
 */
export const useClientTimeline = (clientId: string) => {
    
    // --- ESTADOS ---
    
    // Lista de interações já processadas e prontas para exibir
    const [interactions, setInteractions] = useState<CRMInteraction[]>([]);
    
    // Loading geral da lista (Skeleton initial)
    const [loading, setLoading] = useState(false);
    
    // Loading específico do Agente (Spinner "IA pensando...")
    const [analyzing, setAnalyzing] = useState(false);
    
    // Gestão simples de erro para exibir na UI
    const [error, setError] = useState<string | null>(null);

    // --- ADAPTER (PADRÃO DE PROJETO) ---

    /**
     * Função Pura que converte o dado "feio" do backend no objeto "rico" do frontend.
     * Isso blinda seus componentes visuais de mudanças no banco de dados.
     */
    const adaptToFrontend = (dto: BackendInteractionDto): CRMInteraction => {
        // 1. Normalização do Tipo: Garante que a string do banco vire um Enum válido
        // Prioridade: Metadado > Tipo Raiz > Fallback 'NOTE'
        const rawType = dto.aiMetadata?.originalType || dto.type || 'NOTE';
        
        // Verifica se o tipo existe no nosso Enum, senão vira NOTE (segurança)
        const type = Object.values(InteractionType).includes(rawType as InteractionType)
            ? (rawType as InteractionType)
            : InteractionType.NOTE;

        // 2. Montagem do Objeto Rico
        return {
            id: dto.id,
            clientId, // Injetamos o contexto atual
            userId: dto.userId,
            userName: dto.userName,
            createdAt: dto.createdAt,
            type: type,
            content: dto.content,
            
            // 3. Mapeamento de Inteligência
            // Se não foi manual, assumimos que foi gerado/tocado pelo sistema
            autoGenerated: !dto.aiMetadata?.manual,
            
            // Passamos o metadata completo para componentes avançados usarem (Ex: Cards de Proposta)
            aiMetadata: dto.aiMetadata, 
            
            // Atalho para análise legada (compatibilidade)
            aiAnalysis: dto.aiMetadata?.analysis
        };
    };

    // --- AÇÕES (FETCH & WRITE) ---

    /**
     * Busca o histórico completo do cliente.
     * Deve ser chamado no useEffect da página.
     */
    const fetchTimeline = useCallback(async () => {
        if (!clientId) return;
        
        setLoading(true);
        setError(null);
        
        try {
            // GET /crm/timeline/:clientId
            const response = await api.get<BackendInteractionDto[]>(`/crm/timeline/${clientId}`);
            
            // Passa cada item pelo adaptador antes de salvar no estado
            const adapted = response.data.map(adaptToFrontend);
            
            setInteractions(adapted);
        } catch (err: any) {
            const msg = err.response?.data?.message || 'Erro ao carregar histórico.';
            console.error('❌ Erro no fetchTimeline:', msg);
            setError(msg);
        } finally {
            setLoading(false);
        }
    }, [clientId]);

    /**
     * Envia uma nova mensagem/nota para o Agente.
     * * @param content O texto digitado pelo usuário
     * @param type O canal selecionado (NOTE, CALL, WHATSAPP, etc)
     */
    const registerInteraction = async (content: string, type: InteractionType) => {
        // Ativa o estado "IA Pensando"
        setAnalyzing(true);
        setError(null);

        try {
            // Payload estrito conforme esperado pelo DTO do Backend
            const payload = {
                action: 'LINK_EXISTING', // Estamos na tela do cliente, então é vínculo
                clientId,
                type,
                content
            };

            // POST /crm/interactions
            const response = await api.post<BackendInteractionDto>('/crm/interactions', payload);
            
            // O backend já devolve a interação criada e processada pela IA
            const newInteraction = adaptToFrontend(response.data);

            // Atualiza a lista localmente (Optimistic Update ou Append real)
            setInteractions(prev => [newInteraction, ...prev]);

            // --- PONTO DE DECISÃO DO AGENTE (HUMAN-IN-THE-LOOP) ---
            // Se o backend devolver uma proposta, significa que a IA quer mudar algo no CRM.
            if (response.data.aiMetadata?.proposal) {
                console.log('🤖 PROPOSTA RECEBIDA:', response.data.aiMetadata.proposal);
                
                // TODO: Conectar aqui seu Modal de Confirmação.
                // Exemplo: setPendingProposal(response.data.aiMetadata.proposal)
                // Por enquanto, usamos alert para debug:
                alert(`O Agente sugere: ${response.data.aiMetadata.proposal.reasoning}`);
            }

            return newInteraction;

        } catch (err: any) {
            const msg = err.response?.data?.message || 'Erro ao salvar interação.';
            console.error('❌ Erro no registerInteraction:', msg);
            setError(msg);
            throw err; // Re-lança para o componente tratar se quiser
        } finally {
            setAnalyzing(false);
        }
    };

    return {
        interactions,      // A lista tratada
        loading,           // Loading inicial
        analyzing,         // Loading de processamento da IA
        error,             // Erro legível para UI
        fetchTimeline,     // Função de recarregar
        registerInteraction // Função de enviar
    };
};